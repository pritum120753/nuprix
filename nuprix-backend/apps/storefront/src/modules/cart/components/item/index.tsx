"use client"

import { Table, Text, clx } from "@modules/common/components/ui"
import { updateLineItem } from "@lib/data/cart"
import { HttpTypes } from "@medusajs/types"
import CartItemSelect from "@modules/cart/components/cart-item-select"
import ErrorMessage from "@modules/checkout/components/error-message"
import DeleteButton from "@modules/common/components/delete-button"
import FulfillmentBadge from "@modules/common/components/fulfillment-badge"
import LineItemOptions from "@modules/common/components/line-item-options"
import LineItemPrice from "@modules/common/components/line-item-price"
import LineItemUnitPrice from "@modules/common/components/line-item-unit-price"
import LocalizedClientLink from "@modules/common/components/localized-client-link"
import Spinner from "@modules/common/icons/spinner"
import Thumbnail from "@modules/products/components/thumbnail"
import { getLineItemFulfillmentType } from "@lib/util/product"
import { useState } from "react"

const MAX_QUANTITY_OPTIONS = 10

type ItemProps = {
  item: HttpTypes.StoreCartLineItem
  type?: "full" | "preview"
  currencyCode: string
}

const Item = ({ item, type = "full", currencyCode }: ItemProps) => {
  const [updating, setUpdating] = useState(false)
  const [deleting, setDeleting] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const changeQuantity = async (quantity: number) => {
    setError(null)
    setUpdating(true)

    await updateLineItem({
      lineId: item.id,
      quantity,
    })
      .catch((err) => {
        setError(err.message)
      })
      .finally(() => {
        setUpdating(false)
      })
  }

  // These are UI choices, not an inventory limit. Medusa validates stock when
  // the quantity is updated.
  const quantityOptions = new Set(
    Array.from(
      { length: MAX_QUANTITY_OPTIONS },
      (_, index) => index + 1
    )
  )
  if (item.quantity >= MAX_QUANTITY_OPTIONS) {
    const firstWindowQuantity = Math.max(
      1,
      item.quantity - MAX_QUANTITY_OPTIONS + 1
    )
    const lastWindowQuantity = item.quantity + MAX_QUANTITY_OPTIONS

    for (
      let quantity = firstWindowQuantity;
      quantity <= lastWindowQuantity;
      quantity += 1
    ) {
      quantityOptions.add(quantity)
    }
  }

  return (
    <Table.Row className="w-full" data-testid="product-row">
      <Table.Cell className="!pl-0 p-4 w-24">
        <LocalizedClientLink
          href={`/products/${item.product_handle}`}
          className={clx("flex", {
            "w-16": type === "preview",
            "small:w-24 w-12": type === "full",
          })}
        >
          <Thumbnail
            thumbnail={item.thumbnail}
            images={item.variant?.product?.images}
            size="square"
          />
        </LocalizedClientLink>
      </Table.Cell>

      <Table.Cell className="text-left">
        <Text
          className="txt-medium-plus text-ui-fg-base"
          data-testid="product-title"
        >
          {item.product_title}
        </Text>
        <LineItemOptions variant={item.variant} data-testid="product-variant" />
        <FulfillmentBadge
          type={getLineItemFulfillmentType(item)}
          context="cart"
        />
      </Table.Cell>

      {type === "full" && (
        <Table.Cell>
          <div className="flex gap-2 items-center w-28">
            <DeleteButton
              id={item.id}
              disabled={updating}
              onPendingChange={setDeleting}
              data-testid="product-delete-button"
            />
            <CartItemSelect
              value={item.quantity}
              onChange={(value) => changeQuantity(parseInt(value.target.value))}
              disabled={updating || deleting}
              aria-label={`Quantity for ${item.product_title}`}
              className="w-14 h-10 p-4"
              data-testid="product-select-button"
            >
              {Array.from(quantityOptions)
                .sort((a, b) => a - b)
                .map((quantity) => (
                  <option value={quantity} key={quantity}>
                    {quantity}
                  </option>
                ))}
            </CartItemSelect>
            {updating && (
              <>
                <Spinner aria-hidden="true" />
                <span className="sr-only" role="status">
                  Updating quantity for {item.product_title}
                </span>
              </>
            )}
          </div>
          <ErrorMessage error={error} data-testid="product-error-message" />
        </Table.Cell>
      )}

      {type === "full" && (
        <Table.Cell className="hidden small:table-cell">
          <LineItemUnitPrice
            item={item}
            style="tight"
            currencyCode={currencyCode}
          />
        </Table.Cell>
      )}

      <Table.Cell className="!pr-0">
        <span
          className={clx("!pr-0", {
            "flex flex-col items-end h-full justify-center": type === "preview",
          })}
        >
          {type === "preview" && (
            <span className="flex gap-x-1 ">
              <Text className="text-ui-fg-muted">{item.quantity}x </Text>
              <LineItemUnitPrice
                item={item}
                style="tight"
                currencyCode={currencyCode}
              />
            </span>
          )}
          <LineItemPrice
            item={item}
            style="tight"
            currencyCode={currencyCode}
          />
        </span>
      </Table.Cell>
    </Table.Row>
  )
}

export default Item
